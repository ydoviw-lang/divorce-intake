import { Packer } from 'docx';
import JSZip from 'jszip';
import { supabaseAdmin } from '../../../../lib/supabaseClient';
import { isAuthedRequest } from '../../../../lib/auth';
import { decryptField } from '../../../../lib/crypto';
import { buildSummonsWithNotice, buildVerifiedComplaint, buildSwornAffirmationOfPlaintiff } from '../../../../lib/documents';

export default async function handler(req, res) {
  if (!isAuthedRequest(req)) {
    return res.status(401).json({ error: 'Not authenticated' });
  }
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  const { fileNo } = req.query;

  const { data: row, error } = await supabaseAdmin
    .from('packets')
    .select('*')
    .eq('file_no', fileNo)
    .single();

  if (error || !row) {
    return res.status(404).json({ error: 'Packet not found' });
  }

  if (row.status !== 'approved' && row.status !== 'delivered') {
    return res.status(400).json({ error: 'Only approved packets can generate documents' });
  }

  const packetData = row.data;
  const meta = {
    indexNo: '', // assigned by the court clerk at filing — left blank
    county: req.body?.county || '',
    dateSigned: new Date().toLocaleDateString('en-US'),
    p1SSN: packetData.p1SSNEncrypted ? decryptField(packetData.p1SSNEncrypted) : null,
    p2SSN: packetData.p2SSNEncrypted ? decryptField(packetData.p2SSNEncrypted) : null,
  };

  const docs = {
    'UD-1 Summons with Notice.docx': buildSummonsWithNotice(packetData, meta),
    'UD-2 Verified Complaint.docx': buildVerifiedComplaint(packetData, meta),
    'UD-6 Sworn Affirmation of Plaintiff.docx': buildSwornAffirmationOfPlaintiff(packetData, meta),
  };

  const zip = new JSZip();
  for (const [name, doc] of Object.entries(docs)) {
    const buffer = await Packer.toBuffer(doc);
    zip.file(name, buffer);
  }
  zip.file('READ ME — Preparer Checklist.txt',
    `Documents generated for ${fileNo} — ${packetData.p1Name} & ${packetData.p2Name}\n\n` +
    `Before filing, confirm/complete the following, flagged inline in the documents as [PREPARER]:\n` +
    `- County of filing (index number is assigned by the court clerk)\n` +
    `- Exact residency basis (which spouse, which clause)\n` +
    `- Military service status of Defendant\n` +
    `- Public assistance status\n` +
    `- Attach the parties' written settlement/separation agreement if applicable\n\n` +
    `These three documents (Summons, Verified Complaint, Sworn Affirmation of Plaintiff) start ` +
    `the case. The remaining forms in the packet (Affirmation of Service, Sworn Statement of ` +
    `Removal of Barriers, Note of Issue, Findings of Fact, Judgment of Divorce, Certificate of ` +
    `Dissolution, etc.) come later in the process and aren't generated by this version yet.`
  );

  const zipBuffer = await zip.generateAsync({ type: 'nodebuffer' });

  res.setHeader('Content-Type', 'application/zip');
  res.setHeader('Content-Disposition', `attachment; filename="${fileNo}-documents.zip"`);
  return res.status(200).send(zipBuffer);
}
